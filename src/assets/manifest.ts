const TEXTURE_LODS = [
  { id: 'lod0', triangles: 0, available: true },
  { id: 'lod1', triangles: 0, available: true },
  { id: 'lod2', triangles: 0, available: true },
] as const

type MaterialSeed = {
  id: string
  surface: Exclude<AssetMaterialSurface, 'environment'>
  slug: string
  biome: string
  useCase: string
  repeat: readonly [number, number]
  sourceChecksum: string
  processedChecksum: string
  sourceBytes: number
  runtimeBytes: number
  maxInstances: number
  residentMiB: number
  preload?: boolean
}

function materialAsset(seed: MaterialSeed): AssetManifestEntry {
  const basePath = `/assets/polyhaven/web-1k/${seed.slug}`
  return {
    id: `${seed.id}-web-1k`,
    biome: seed.biome,
    useCase: seed.useCase,
    deterministicVariants: [seed.slug],
    provider: 'polyhaven',
    polyHavenSlug: seed.slug,
    sourceUrl: `https://polyhaven.com/a/${seed.slug}`,
    license: 'CC0-1.0',
    attribution: `Poly Haven — ${seed.slug} (CC0 1.0)`,
    sourceChecksum: seed.sourceChecksum,
    processedChecksum: seed.processedChecksum,
    pack: 'web-1k',
    fileSizes: { sourceBytes: seed.sourceBytes, processedBytes: seed.runtimeBytes, runtimeBytes: seed.runtimeBytes },
    lods: TEXTURE_LODS,
    fallback: 'procedural',
    runtimeBudget: { maxInstances: seed.maxInstances, residentMiB: seed.residentMiB, preload: seed.preload ?? true, intendedUse: seed.useCase },
    runtime: {
      kind: 'material',
      surface: seed.surface,
      repeat: seed.repeat,
      files: [
        { role: 'albedo', path: `${basePath}/albedo.webp`, colorSpace: 'srgb' },
        { role: 'normal', path: `${basePath}/normal.webp`, colorSpace: 'linear' },
        { role: 'roughness', path: `${basePath}/roughness.webp`, colorSpace: 'linear' },
      ],
    },
  }
}

